package lesson7;

public class Employee {
    private String name;
    private String lastName;
    private String surname;
    private String jobTitle;
    private String mail;
    private int phoneNumber;
    private int age;

    public Employee(String name, String lastName, String surname, String jobTitle, String mail, int phoneNumber, int age) {
        this.name = name;
        this.lastName = lastName;
        this.surname = surname;
        this.jobTitle = jobTitle;
        this.mail = mail;
        this.phoneNumber = phoneNumber;
        this.age = age;
    }
}
